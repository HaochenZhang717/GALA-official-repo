"""
EvalAligner — an evaluation-only text<->time-series aligner that shares no
weights, no architecture family, and no pretraining pipeline with the method
under test (EmbeddingGemma-300M + Chronos-2).

Why this exists
---------------
FID / CTTP / JFTSD all live in the embedding space of a contrastively aligned
dual encoder. Until now that encoder was `aligner_v7`, i.e. the very model the
generator is conditioned on (in the tune-both arm, literally the same
checkpoint file). Any metric computed that way is circular. This module builds
an independent scorer:

  * time-series side : dilated 1-D CNN trained FROM SCRATCH. No pretrained
                       time-series backbone at all, hence zero Chronos-2
                       lineage.
  * text side        : BAAI/bge-large-en-v1.5 by default (BertModel, 24 layers,
                       335M params) adapted with LoRA, base weights frozen.
                       Bidirectional encoder / WordPiece / absolute positions —
                       a different architecture family and a different
                       pretraining pipeline from Gemma. Comparable capacity
                       (335M vs 303M) so the scorer cannot be dismissed as
                       under-powered.
  * objective        : symmetric multi-positive InfoNCE only. No diffusion
                       term, so the scorer is never trained generatively.

Deliberately NOT used on the text side: any Qwen embedding model. The captions
were generated by `Qwen/Qwen3-8B`, so a Qwen-family scorer would reintroduce a
lineage the reviewer could attack.

Honest scope of the independence claim: this removes shared weights, shared
architecture and shared pretraining. It does not remove the fact that the
scorer is itself trained with a text<->TS contrastive objective on the same
captions — report the observation-space metrics (MDD / ACD / SD / KD, MMD,
discriminative score) alongside it, not instead of it.

The multi-positive mask mirrors `aligner_v7` so that identical series appearing
under different captions are not treated as negatives.
"""

from __future__ import annotations

import math
from pathlib import Path
from typing import Sequence

import torch
import torch.distributed as dist
import torch.nn as nn
import torch.nn.functional as F
from peft import LoraConfig, get_peft_model
from torch.distributed.nn.functional import all_gather as _all_gather_with_grad
from transformers import AutoModel, AutoTokenizer

DEFAULT_TEXT_MODEL = "BAAI/bge-large-en-v1.5"

# BERT attention projections. `dense` is intentionally excluded: BERT has three
# distinct modules named `dense` per layer, and matching all of them triples the
# adapter size for no measurable gain here.
DEFAULT_TEXT_LORA_TARGETS = ("query", "key", "value")


def _gather_features_with_grad(t: torch.Tensor) -> torch.Tensor:
    if not (dist.is_available() and dist.is_initialized()):
        return t
    if dist.get_world_size() == 1:
        return t
    return torch.cat(_all_gather_with_grad(t.contiguous()), dim=0)


def _gather_no_grad(t: torch.Tensor) -> torch.Tensor:
    if not (dist.is_available() and dist.is_initialized()):
        return t
    world_size = dist.get_world_size()
    if world_size == 1:
        return t
    gathered = [torch.empty_like(t) for _ in range(world_size)]
    dist.all_gather(gathered, t.contiguous())
    return torch.cat(gathered, dim=0)


class ResidualDilatedBlock(nn.Module):
    """Pre-activation residual block with dilated convolutions.

    GroupNorm rather than BatchNorm on purpose: an evaluation encoder must give
    the same embedding for a series regardless of which other samples share its
    batch, otherwise FID/CTTP would depend on batching order.
    """

    def __init__(self, channels: int, kernel_size: int, dilation: int, dropout: float, num_groups: int = 8):
        super().__init__()
        padding = dilation * (kernel_size - 1) // 2
        groups = min(num_groups, channels)
        self.norm1 = nn.GroupNorm(groups, channels)
        self.conv1 = nn.Conv1d(channels, channels, kernel_size, padding=padding, dilation=dilation)
        self.norm2 = nn.GroupNorm(groups, channels)
        self.conv2 = nn.Conv1d(channels, channels, kernel_size, padding=padding, dilation=dilation)
        self.drop = nn.Dropout(dropout)

    def forward(self, x: torch.Tensor) -> torch.Tensor:
        h = self.conv1(F.gelu(self.norm1(x)))
        h = self.drop(h)
        h = self.conv2(F.gelu(self.norm2(h)))
        return x + h


class CNNTimeSeriesEncoder(nn.Module):
    """From-scratch dilated 1-D CNN over a single variate.

    Multivariate input is encoded one variate at a time and mean-pooled across
    variates, matching how `aligner_v7` aggregates Chronos variate tokens, so
    the two scorers see the same information layout.

    Normalization is a dataset-level global z-score (not per-sample instance
    norm) so that absolute level survives into the embedding — the captions talk
    about absolute values ("declines to a low of around 13.718"), and a scorer
    blind to level could not tell adherence from non-adherence.
    """

    def __init__(
        self,
        hidden_channels: int = 256,
        kernel_size: int = 3,
        dilations: Sequence[int] = (1, 2, 4, 8),
        dropout: float = 0.1,
        stem_kernel_size: int = 7,
        global_mean: float = 0.0,
        global_std: float = 1.0,
    ):
        super().__init__()
        self.register_buffer("global_mean", torch.tensor(float(global_mean), dtype=torch.float32))
        self.register_buffer("global_std", torch.tensor(max(float(global_std), 1e-5), dtype=torch.float32))

        self.stem = nn.Conv1d(1, hidden_channels, stem_kernel_size, padding=stem_kernel_size // 2)
        self.blocks = nn.ModuleList(
            [ResidualDilatedBlock(hidden_channels, kernel_size, d, dropout) for d in dilations]
        )
        self.out_norm = nn.GroupNorm(min(8, hidden_channels), hidden_channels)
        # mean + max + std pooling over time
        self.feat_dim = 3 * hidden_channels

    def forward(self, series: torch.Tensor) -> torch.Tensor:
        """series: (B, V, L) -> (B, feat_dim)"""
        bsz, n_var, seq_len = series.shape
        x = series.float()
        x = (x - self.global_mean) / self.global_std
        x = x.reshape(bsz * n_var, 1, seq_len)

        x = self.stem(x)
        for block in self.blocks:
            x = block(x)
        x = F.gelu(self.out_norm(x))

        pooled = torch.cat(
            [x.mean(dim=-1), x.amax(dim=-1), x.std(dim=-1, unbiased=False)],
            dim=-1,
        )  # (B*V, 3C)
        return pooled.reshape(bsz, n_var, -1).mean(dim=1)


class EvalAligner(nn.Module):
    """Independent text<->TS dual encoder used only for evaluation."""

    def __init__(
        self,
        text_model_id: str = DEFAULT_TEXT_MODEL,
        proj_dim: int = 128,
        text_dtype: torch.dtype = torch.float32,
        device: str | torch.device = "cpu",
        init_temperature: float = 0.07,
        min_temperature: float = 0.03,
        hf_token: str | None = None,
        text_lora_r: int = 8,
        text_lora_alpha: int = 16,
        text_lora_dropout: float = 0.05,
        text_lora_target_modules: Sequence[str] = DEFAULT_TEXT_LORA_TARGETS,
        text_pooling: str = "cls",
        text_max_length: int = 512,
        text_prefix: str = "",
        cnn_hidden_channels: int = 256,
        cnn_kernel_size: int = 3,
        cnn_dilations: Sequence[int] = (1, 2, 4, 8),
        cnn_dropout: float = 0.1,
        ts_global_mean: float = 0.0,
        ts_global_std: float = 1.0,
    ):
        super().__init__()
        self._device = torch.device(device)

        if text_pooling not in ("cls", "mean"):
            raise ValueError(f"text_pooling must be 'cls' or 'mean', got {text_pooling!r}")
        self.text_pooling = text_pooling
        self.text_max_length = int(text_max_length)
        self.text_prefix = text_prefix

        # ---------- text side: frozen BERT-family base + LoRA ----------
        self.tokenizer = AutoTokenizer.from_pretrained(text_model_id, token=hf_token)
        text_base = AutoModel.from_pretrained(text_model_id, torch_dtype=text_dtype, token=hf_token)
        text_dim = int(text_base.config.hidden_size)
        lora_cfg = LoraConfig(
            r=text_lora_r,
            lora_alpha=text_lora_alpha,
            lora_dropout=text_lora_dropout,
            target_modules=list(text_lora_target_modules),
            bias="none",
        )
        self.text_encoder = get_peft_model(text_base, lora_cfg)
        self.text_encoder.to(self._device)

        # ---------- time-series side: CNN trained from scratch ----------
        self.ts_encoder = CNNTimeSeriesEncoder(
            hidden_channels=cnn_hidden_channels,
            kernel_size=cnn_kernel_size,
            dilations=tuple(cnn_dilations),
            dropout=cnn_dropout,
            global_mean=ts_global_mean,
            global_std=ts_global_std,
        )

        # ---------- projectors to the shared space ----------
        self.text_proj = nn.Linear(text_dim, proj_dim)
        self.ts_proj = nn.Sequential(
            nn.Linear(self.ts_encoder.feat_dim, cnn_hidden_channels),
            nn.GELU(),
            nn.Linear(cnn_hidden_channels, proj_dim),
        )

        self.logit_scale = nn.Parameter(torch.tensor(math.log(1.0 / init_temperature)))
        self.min_temperature = min_temperature
        self.max_logit_scale = math.log(1.0 / min_temperature)

        self.proj_dim = proj_dim
        self.text_model_id = text_model_id
        self.to(self._device)

    @property
    def device(self) -> torch.device:
        return next(self.text_proj.parameters()).device

    def trainable_parameters(self):
        return [p for p in self.parameters() if p.requires_grad]

    def print_trainable_parameters(self) -> None:
        n_text = sum(p.numel() for p in self.text_encoder.parameters() if p.requires_grad)
        n_ts = sum(p.numel() for p in self.ts_encoder.parameters() if p.requires_grad)
        n_proj = sum(p.numel() for n, p in self.named_parameters() if p.requires_grad and "proj" in n)
        print(f"[eval-aligner] trainable: text-LoRA={n_text:,}  cnn={n_ts:,}  projectors={n_proj:,}")

    def encode_text(self, captions: Sequence[str]) -> torch.Tensor:
        texts = [self.text_prefix + c for c in captions] if self.text_prefix else list(captions)
        batch = self.tokenizer(
            texts,
            padding=True,
            truncation=True,
            return_tensors="pt",
            max_length=self.text_max_length,
        )
        batch = {k: v.to(self.device) for k, v in batch.items()}
        out = self.text_encoder(**batch)
        last_hidden = out.last_hidden_state
        if self.text_pooling == "cls":
            # BGE's own convention; e5/mpnet checkpoints want text_pooling='mean'.
            pooled = last_hidden[:, 0]
        else:
            mask = batch["attention_mask"].unsqueeze(-1).to(last_hidden.dtype)
            pooled = (last_hidden * mask).sum(dim=1) / mask.sum(dim=1).clamp(min=1e-9)
        emb = self.text_proj(pooled.float())
        return F.normalize(emb, dim=-1)

    def encode_time_series(self, series: torch.Tensor) -> torch.Tensor:
        """series: (B, V, L) -> (B, proj_dim)"""
        if series.device != self.device:
            series = series.to(self.device)
        feat = self.ts_encoder(series.float())
        return F.normalize(self.ts_proj(feat), dim=-1)

    # Alias so this drops straight into ConTSGMetricsAccumulator, which calls
    # `embedder.encode_series(...)`.
    def encode_series(self, series: torch.Tensor) -> torch.Tensor:
        return self.encode_time_series(series)

    @staticmethod
    def _multi_positive_ce(logits: torch.Tensor, positive_mask: torch.Tensor) -> torch.Tensor:
        log_prob = F.log_softmax(logits, dim=1)
        pos_count = positive_mask.sum(dim=1).clamp(min=1)
        loss_i = -(log_prob * positive_mask.float()).sum(dim=1) / pos_count.float()
        return loss_i.mean()

    def forward(
        self,
        captions: Sequence[str],
        time_series: torch.Tensor,
        series_hash: torch.Tensor | None = None,
        gather: bool = True,
    ) -> dict:
        text_emb = self.encode_text(captions)
        ts_emb = self.encode_time_series(time_series)

        if series_hash is None:
            series_hash = torch.arange(text_emb.size(0), device=text_emb.device, dtype=torch.long)
        else:
            series_hash = series_hash.to(text_emb.device, dtype=torch.long)

        if gather:
            text_all = _gather_features_with_grad(text_emb)
            ts_all = _gather_features_with_grad(ts_emb)
            hash_all = _gather_no_grad(series_hash)
        else:
            text_all, ts_all, hash_all = text_emb, ts_emb, series_hash

        logit_scale = self.logit_scale.clamp(max=self.max_logit_scale).exp()
        sim = text_all @ ts_all.t()
        logits = logit_scale * sim
        pos_mask = hash_all[:, None].eq(hash_all[None, :])

        loss_t2s = self._multi_positive_ce(logits, pos_mask)
        loss_s2t = self._multi_positive_ce(logits.t(), pos_mask.t())
        loss = 0.5 * (loss_t2s + loss_s2t)

        with torch.no_grad():
            cosine = sim.diagonal()
            acc_t2s = hash_all[logits.argmax(dim=-1)].eq(hash_all).float().mean()
            acc_s2t = hash_all[logits.argmax(dim=0)].eq(hash_all).float().mean()

        return {
            "loss": loss,
            "loss_t2s": loss_t2s,
            "loss_s2t": loss_s2t,
            "cosine": cosine,
            "acc_t2s": acc_t2s,
            "acc_s2t": acc_s2t,
            "logit_scale": logit_scale.detach(),
            "num_positive_pairs": pos_mask.float().sum().detach(),
            "text_emb": text_all,
            "ts_emb": ts_all,
        }


def build_eval_aligner_from_ckpt(
    ckpt_path: str | Path,
    device: str | torch.device,
    hf_token: str | None = None,
) -> EvalAligner:
    """Rebuild an EvalAligner from a training checkpoint."""
    payload = torch.load(str(ckpt_path), map_location="cpu", weights_only=False)
    args = payload["args"]
    state = payload.get("aligner_trainable_state")
    if state is None:
        raise KeyError(f"{ckpt_path}: checkpoint missing 'aligner_trainable_state'")

    # The z-score buffers are not parameters, so they are stored separately.
    # Reconstructing with the wrong stats would silently shift every embedding.
    stats = payload.get("ts_stats")
    if stats is None:
        raise KeyError(
            f"{ckpt_path}: checkpoint missing 'ts_stats'; refusing to fall back to "
            "mean=0/std=1, which would silently change every embedding."
        )

    model = EvalAligner(
        text_model_id=args["text_model_id"],
        proj_dim=int(args["proj_dim"]),
        text_dtype=getattr(torch, args.get("text_dtype", "float32")),
        device=device,
        init_temperature=float(args["init_temperature"]),
        min_temperature=float(args["min_temperature"]),
        hf_token=hf_token,
        text_lora_r=int(args["text_lora_r"]),
        text_lora_alpha=int(args["text_lora_alpha"]),
        text_lora_dropout=float(args["text_lora_dropout"]),
        text_lora_target_modules=tuple(args["text_lora_target_modules"]),
        text_pooling=args.get("text_pooling", "cls"),
        text_max_length=int(args.get("text_max_length", 512)),
        text_prefix=args.get("text_prefix", "") or "",
        cnn_hidden_channels=int(args["cnn_hidden_channels"]),
        cnn_kernel_size=int(args["cnn_kernel_size"]),
        cnn_dilations=tuple(args["cnn_dilations"]),
        cnn_dropout=float(args["cnn_dropout"]),
        ts_global_mean=float(stats["mean"]),
        ts_global_std=float(stats["std"]),
    )

    model_state = model.state_dict()
    missing_shapes = [
        k for k, v in state.items()
        if k in model_state and tuple(model_state[k].shape) != tuple(v.shape)
    ]
    if missing_shapes:
        raise RuntimeError(f"{ckpt_path}: shape mismatch for {missing_shapes[:5]}")
    unknown = [k for k in state if k not in model_state]
    if unknown:
        raise RuntimeError(f"{ckpt_path}: checkpoint has {len(unknown)} unknown keys, e.g. {unknown[:5]}")

    model.load_state_dict(state, strict=False)
    model.eval()
    for p in model.parameters():
        p.requires_grad_(False)
    return model


class EvalAlignerMetricEmbedder:
    """Drop-in replacement for AlignerV6/V7MetricEmbedder in the gen-eval path.

    Exposes exactly `encode_text` / `encode_series`, which is all
    `ConTSGMetricsAccumulator` needs.
    """

    def __init__(self, ckpt_path: str | Path, device: torch.device, hf_token: str | None = None):
        self.model = build_eval_aligner_from_ckpt(ckpt_path, device=device, hf_token=hf_token)
        self.device = torch.device(device)
        print(f"[EvalAlignerMetricEmbedder] loaded {ckpt_path} (text={self.model.text_model_id}, d={self.model.proj_dim})")

    @torch.no_grad()
    def encode_text(self, captions: Sequence[str]) -> torch.Tensor:
        return self.model.encode_text(list(captions))

    @torch.no_grad()
    def encode_series(self, series_bvl: torch.Tensor) -> torch.Tensor:
        return self.model.encode_time_series(series_bvl)
